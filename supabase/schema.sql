-- Neon Highway arcade leaderboard schema
create table if not exists public.game_scores (
  id bigint generated by default as identity primary key,
  player_name text not null default 'Driver' check (char_length(player_name) between 1 and 16),
  score integer not null check (score between 0 and 100000000),
  targets_hit integer not null default 0 check (targets_hit between 0 and 1000000),
  distance integer not null default 0 check (distance between 0 and 100000000),
  created_at timestamptz not null default now()
);

alter table public.game_scores enable row level security;

grant select, insert on public.game_scores to anon, authenticated;
grant usage, select on sequence public.game_scores_id_seq to anon, authenticated;

create policy "Anyone can read leaderboard"
on public.game_scores for select to anon, authenticated
using (true);

create policy "Anyone can submit a score"
on public.game_scores for insert to anon, authenticated
with check (
  char_length(player_name) between 1 and 16
  and score between 0 and 100000000
  and targets_hit between 0 and 1000000
  and distance between 0 and 100000000
);

create index if not exists game_scores_score_created_idx
on public.game_scores (score desc, created_at asc);
